"""Split the selected videos into train / calib / test **by video** (never by clip), stratified by camera.

  train  pool for the k teaching examples and the active-learning questions; also the only source for ROI choice
  calib  `random`-provenance calibration labels (conformal tau); must stay disjoint from anything used for fitting
  test   held-out evaluation (F1, empirical false-alarm rate vs alpha)

Every camera gets >= 1 train video (its ROI is chosen from train only) and, when it has >= 3 videos, >= 1 calib and
>= 1 test video.  Among the camera-stratified assignments, a seeded random search picks the one whose per-split share
of annotated concept instances is closest to the target fractions (so no split starves of a scarce concept).

    uv run --project engine python -m eval.data.splits [--seed 0]
"""
from __future__ import annotations

import argparse
import random
import sys
from collections import defaultdict

from .config import SPLITS, dump_yaml, load_yaml

FRACTIONS = {"train": 0.45, "calib": 0.25, "test": 0.30}


def _allocate(n: int, fractions: dict[str, float]) -> dict[str, int]:
    """Largest-remainder allocation of `n` videos of one camera to splits, train >= 1 and calib/test >= 1 if n >= 3."""
    raw = {s: n * f for s, f in fractions.items()}
    out = {s: int(v) for s, v in raw.items()}
    for s in sorted(raw, key=lambda s: (-(raw[s] - out[s]), SPLITS.index(s)))[: n - sum(out.values())]:
        out[s] += 1
    if n >= 3:
        for s in ("calib", "test"):
            while out[s] < 1:
                donor = max(out, key=lambda k: out[k])
                out[donor] -= 1
                out[s] += 1
    while out["train"] < 1 and n >= 1:
        donor = max((k for k in out if k != "train"), key=lambda k: out[k])
        out[donor] -= 1
        out["train"] += 1
    return out


def assign_splits(videos: list[dict], seed: int = 0, fractions: dict[str, float] | None = None, tries: int = 3000) -> dict[str, str]:
    """videos: dicts with `stem`, `camera`, `instances` (concept -> count). Returns stem -> split."""
    fractions = fractions or FRACTIONS
    by_cam: dict[str, list[dict]] = defaultdict(list)
    for v in videos:
        by_cam[v["camera"]].append(v)
    concepts = sorted({c for v in videos for c in v.get("instances", {})})
    totals = {c: sum(v["instances"].get(c, 0) for v in videos) or 1 for c in concepts}
    quota = {cam: _allocate(len(vs), fractions) for cam, vs in by_cam.items()}
    rng = random.Random(seed)
    best, best_cost = None, float("inf")
    for _ in range(tries):
        assign: dict[str, str] = {}
        for cam in sorted(by_cam):
            order = sorted(by_cam[cam], key=lambda v: v["stem"])
            rng.shuffle(order)
            i = 0
            for s in SPLITS:
                for v in order[i:i + quota[cam][s]]:
                    assign[v["stem"]] = s
                i += quota[cam][s]
        cost = 0.0
        for c in concepts:
            for s in SPLITS:
                share = sum(v["instances"].get(c, 0) for v in videos if assign[v["stem"]] == s) / totals[c]
                cost += (share - fractions[s]) ** 2
        if cost < best_cost - 1e-12:
            best, best_cost = assign, cost
    assert best is not None
    return best


def load_split_map() -> dict[str, str]:
    d = load_yaml("splits.yaml")["splits"]
    return {stem: s for s, stems in d.items() for stem in stems}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args(argv)
    videos = load_yaml("videos.yaml")["videos"]
    assign = assign_splits(videos, args.seed)
    by_split = {s: sorted(stem for stem, sp in assign.items() if sp == s) for s in SPLITS}
    inst = {s: {} for s in SPLITS}
    for v in videos:
        for c, n in v["instances"].items():
            inst[assign[v["stem"]]][c] = inst[assign[v["stem"]]].get(c, 0) + n
    dump_yaml("splits.yaml", {
        "seed": args.seed, "fractions": FRACTIONS, "unit": "video (a video is in exactly one split)",
        "splits": by_split, "annotated_instances_per_split": inst,
    }, header="# Generated by `python -m eval.data.splits`. Split is by VIDEO, stratified by camera.\n")
    for s in SPLITS:
        cams = sorted({stem.split(".")[-1] for stem in by_split[s]})
        print(f"{s:6s} {len(by_split[s]):2d} videos cams={cams} instances={inst[s]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
