"""Video metadata via the bundled ffmpeg (no ffprobe available): size, fps, duration.

    uv run --project engine python -m eval.data.probe   # writes eval/data/video_info.yaml for every downloaded video
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import imageio_ffmpeg

from . import paths
from .config import dump_yaml, load_yaml

_DUR = re.compile(r"Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)")
_STREAM = re.compile(r"Stream #\S+: Video: .*?, (\d{2,5})x(\d{2,5})")
_FPS = re.compile(r"(\d+(?:\.\d+)?) fps")


def parse_ffmpeg_info(stderr: str) -> dict:
    """Parse `ffmpeg -i` stderr into width/height/fps/duration_ms."""
    dur = _DUR.search(stderr)
    st = _STREAM.search(stderr)
    if not dur or not st:
        raise ValueError("could not parse ffmpeg -i output")
    h, m, s = dur.groups()
    fps = _FPS.search(stderr[st.start():])
    return {
        "width": int(st.group(1)), "height": int(st.group(2)),
        "fps": float(fps.group(1)) if fps else None,
        "duration_ms": int(round((int(h) * 3600 + int(m) * 60 + float(s)) * 1000)),
    }


def probe(path: Path) -> dict:
    r = subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-i", str(path)], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    return parse_ffmpeg_info(r.stderr)


def load_info() -> dict[str, dict]:
    try:
        return load_yaml("video_info.yaml")["videos"]
    except FileNotFoundError:
        return {}


def main() -> int:
    info = load_info()
    for v in load_yaml("videos.yaml")["videos"]:
        f = paths.videos_dir() / f"{v['stem']}.r13.avi"
        if f.is_file() and v["stem"] not in info:
            info[v["stem"]] = probe(f)
            print(v["stem"], info[v["stem"]])
    dump_yaml("video_info.yaml", {"videos": dict(sorted(info.items()))},
              header="# Generated by `python -m eval.data.probe` (ffmpeg -i); width/height/fps/duration per downloaded video.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
