// Prebuild for the opt-in browser Z3 (SPEC 8). Runs before `next build` (npm "prebuild" hook).
//
// Release R4 (the default; SHOWCASE_RELEASE unset or R4): every earlier release deploys no Z3 file at all.
//   1. copies z3-built.js and z3-built.wasm from node_modules/z3-solver (pinned to 5.3.1) to public/z3/5.3.1/ - the
//      files must stay separate scripts: Emscripten starts its pthread workers from z3-built.js, so webpack must never
//      bundle it;
//   2. bundles lib/synth/z3/worker.ts with esbuild into a classic (IIFE) worker, public/z3/5.3.1/z3-worker.<hash>.js;
//   3. writes .env.production.local / .env.development.local with the public URL of that worker and the estimated
//      transfer size, which Next inlines into the client (the page does not fetch anything under /z3/ before the click).
// All outputs are gitignored (public/z3/, .env.*.local). Nothing here makes a network request.
import { brotliCompressSync, constants } from 'node:zlib'
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { build } from 'esbuild'

const Z3_VERSION = '5.3.1'
const root = resolve(import.meta.dirname, '..', '..')
const outDir = join(root, 'public', 'z3')
const versionDir = join(outDir, Z3_VERSION)
const envFiles = ['.env.production.local', '.env.development.local'].map((f) => join(root, f))
const GENERATED_MARK = '# generated by scripts/z3/prebuild.mjs - do not edit\n'

const release = process.env.SHOWCASE_RELEASE || 'R4' // the default release ships Z3, like next.config.js
if (!['R1', 'R2', 'R3', 'R4'].includes(release)) throw new Error(`SHOWCASE_RELEASE=${JSON.stringify(release)} is not valid`)

function removeGenerated() {
  rmSync(outDir, { recursive: true, force: true })
  for (const f of envFiles) {
    if (existsSync(f) && readFileSync(f, 'utf-8').startsWith(GENERATED_MARK)) rmSync(f)
  }
}

if (release !== 'R4') {
  removeGenerated()
  console.log(`z3 prebuild: release ${release} deploys no Z3 (R4 only); public/z3/ removed`)
  process.exit(0)
}

const pkgDir = join(root, 'node_modules', 'z3-solver')
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf-8'))
if (pkg.version !== Z3_VERSION) throw new Error(`z3-solver ${pkg.version} is installed; this build is pinned to ${Z3_VERSION}`)

rmSync(outDir, { recursive: true, force: true })
mkdirSync(versionDir, { recursive: true })
for (const f of ['z3-built.js', 'z3-built.wasm']) copyFileSync(join(pkgDir, 'build', f), join(versionDir, f))

const bundle = await build({
  entryPoints: [join(root, 'lib', 'synth', 'z3', 'worker.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  define: { global: 'globalThis' }, // z3-solver's browser entry reads `global.initZ3`
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
})
const code = bundle.outputFiles[0].contents
const hash = createHash('sha256').update(code).digest('hex').slice(0, 10)
const workerName = `z3-worker.${hash}.js`
writeFileSync(join(versionDir, workerName), code)

// Estimated transfer size with brotli at a CDN-typical quality (the deployed figure must be measured on the deployment).
const br = (buf) => brotliCompressSync(buf, { params: { [constants.BROTLI_PARAM_QUALITY]: 5, [constants.BROTLI_PARAM_LGWIN]: 24, [constants.BROTLI_PARAM_SIZE_HINT]: buf.length } }).length
const transfer = ['z3-built.wasm', 'z3-built.js', workerName].reduce((n, f) => n + br(readFileSync(join(versionDir, f))), 0)
const transferMb = Math.max(1, Math.ceil(transfer / 2 ** 20))

const env = `${GENERATED_MARK}NEXT_PUBLIC_Z3_WORKER=/z3/${Z3_VERSION}/${workerName}\nNEXT_PUBLIC_Z3_TRANSFER_MB=${transferMb}\n`
for (const f of envFiles) writeFileSync(f, env)

const sizes = readdirSync(versionDir).map((f) => `${f} ${(statSync(join(versionDir, f)).size / 2 ** 20).toFixed(2)} MiB`)
console.log(`z3 prebuild: release R4, z3-solver ${Z3_VERSION}; public/z3/${Z3_VERSION}/: ${sizes.join(', ')}; estimated transfer ~${transferMb} MB (brotli q5)`)
